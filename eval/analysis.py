"""Offline analysis: oracle tables vs the pre-flight probe's predictions. Writes eval/analysis.md.
Usage: analysis.py [split] [probe-variant ...]   (default: tune, variant 3x2; heldout is for the verifier only)
Reads eval/oracle/*.json and eval/probe/<variant>/<id>.prune.json (from `fit4 --probe-only`)."""
import json, sys
from pathlib import Path

EVAL = Path(__file__).resolve().parent
split = sys.argv[1] if len(sys.argv) > 1 else "tune"
variants = sys.argv[2:] or ["3x2"]
wins = [w for w in json.load(open(EVAL / "windows.json")) if w["split"] == split]
out = [f"# Offline analysis ({split} windows)\n",
       "Sources: `eval/oracle/*.json` (baseline sweep, ground truth for every candidate's size-fitted screening score) and "
       "`eval/probe/<variant>/<id>.prune.json` (the probe's predictions). Generated by `eval/analysis.py`.\n"]

def label_key(lab):  # oracle labels can carry a fractional fps suffix (vp9-720p30.0002)
    import re
    return re.sub(r"(p\d+)\.\d+$", r"\1", lab)

orc = {}
for w in wins:
    o = json.load(open(EVAL / "oracle" / f"{w['id']}.json"))["dump"]
    cs = [c for c in o["candidates"] if not c["final"]]
    orc[w["id"]] = {label_key(c["label"]): c for c in cs}

out.append("## Where the oracle's work went\n")
out.append("| window | total job-s | screening | finals | retries on feasible | infeasible | pass-1 repeats (reusable) | pass-1 all | scoring |\n|---|---|---|---|---|---|---|---|---|")
for w in wins:
    o = json.load(open(EVAL / "oracle" / f"{w['id']}.json"))["dump"]
    cs = o["candidates"]
    tot = sum(c["seconds"] + c.get("score_seconds", 0) for c in cs)
    scr = sum(c["seconds"] + c.get("score_seconds", 0) for c in cs if not c["final"])
    fin = tot - scr
    retry = sum(t["seconds"] for c in cs for t in c["tries"][1:] if not c["failed_to_fit"])
    inf = sum(c["seconds"] for c in cs if c["failed_to_fit"])
    p1r = sum(t["pass1_s"] for c in cs for t in c["tries"][1:] if t.get("pass1_s"))
    p1 = sum(t["pass1_s"] for c in cs for t in c["tries"] if t.get("pass1_s"))
    sc = sum(c.get("score_seconds", 0) for c in cs)
    out.append(f"| {w['id']} | {tot:.0f} | {scr:.0f} | {fin:.0f} | {retry:.0f} ({100*retry/tot:.0f}%) | {inf:.0f} ({100*inf/tot:.0f}%) | {p1r:.0f} ({100*p1r/tot:.1f}%) | {p1:.0f} ({100*p1/tot:.0f}%) | {sc:.0f} ({100*sc/tot:.0f}%) |")

for var in variants:
    out.append(f"\n## Probe variant `{var}`: would the pruning keep the winner?\n")
    out.append("Margin 1.5 dB, at least 4 kept (the shipped defaults at the time of the run). 'top-N cover' = the best oracle score among the probe's N highest predictions, as a gap to the oracle's best (dB; 0 = the oracle winner is among them).\n")
    out.append("| window | oracle winner (dB) | kept | winner kept | best kept gap dB | oracle job-s in dropped | share of screening | top-1 gap | top-2 gap | top-3 gap |\n|---|---|---|---|---|---|---|---|---|---|")
    detail = []
    for w in wins:
        pp = EVAL / "probe" / var / f"{w['id']}.prune.json"
        if not pp.exists():
            out.append(f"| {w['id']} | (no probe) |"); continue
        pr = json.load(open(pp))
        cs = orc[w["id"]]
        ok = {k: c for k, c in cs.items() if not c["failed_to_fit"]}
        bk = max(ok, key=lambda k: ok[k]["xpsnr_yuv"]); best = ok[bk]["xpsnr_yuv"]
        keep = {d["label"] for d in pr if d["keep"]}
        dropped = sum(c["seconds"] + c.get("score_seconds", 0) for k, c in cs.items() if k not in keep)
        scr = sum(c["seconds"] + c.get("score_seconds", 0) for c in cs.values())
        bestkept = max((ok[k]["xpsnr_yuv"] for k in keep if k in ok), default=None)
        ranked = sorted((d for d in pr if d["predicted"] is not None), key=lambda d: -d["predicted"])
        def topn(n):
            vals = [ok[d["label"]]["xpsnr_yuv"] for d in ranked[:n] if d["label"] in ok]
            return "-" if not vals else f"{best - max(vals):.2f}"
        out.append(f"| {w['id']} | {bk} {best:.2f} | {len(keep)} | {'yes' if bk in keep else 'NO'} | {'-' if bestkept is None else f'{best - bestkept:.2f}'} | {dropped:.0f} | {100*dropped/scr:.0f}% | {topn(1)} | {topn(2)} | {topn(3)} |")
        rows = [f"**{w['id']}**\n\n| candidate | predicted | oracle | err | kept | reason |\n|---|---|---|---|---|---|"]
        for d in sorted(pr, key=lambda d: -(d["predicted"] if d["predicted"] is not None else -99)):
            p = d["predicted"]; c = cs.get(d["label"]); o = None if c is None or c["failed_to_fit"] else c["xpsnr_yuv"]
            err = "" if (p is None or o is None) else f"{p - o:+.2f}"
            rows.append(f"| {d['label']} | {'-' if p is None else f'{p:.2f}'} | {'never fit' if (c and c['failed_to_fit']) else ('-' if o is None else f'{o:.2f}')} | {err} | {'yes' if d['keep'] else 'no'} | {d['reason'][:70]} |")
        detail.append("\n".join(rows))
    out.append("")
    out.extend(x + "\n" for x in detail)
(EVAL / "analysis.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
